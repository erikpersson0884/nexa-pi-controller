  function translateTextNode(node, language) {
    const parent = node.parentElement;
    if (parent && (
      userTextClasses.some(className => className !== 'chip-label' && parent.closest(`.${className}`))
      || (parent.closest('.chip-label') && parent.closest('.outlet-chip[data-unit]'))
    )) return;
    let record = originalText.get(node);
    if (!record) {
      record = {source: node.nodeValue, translated: node.nodeValue};
      originalText.set(node, record);
    } else if (node.nodeValue !== record.translated) {
      record.source = node.nodeValue;
    }
    const translated = translateValue(record.source, language);
    record.translated = translated;
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }

  function translateAttribute(element, attribute, language) {
    const current = element.getAttribute(attribute);
    if (current === null) return;
    let attributes = originalAttributes.get(element);
    if (!attributes) {
      attributes = new Map();
      originalAttributes.set(element, attributes);
    }
    let record = attributes.get(attribute);
    if (!record) {
      record = {source: current, translated: current};
      attributes.set(attribute, record);
    } else if (current !== record.translated) {
      record.source = current;
    }
    const translated = translateValue(record.source, language);
    record.translated = translated;
    if (translated !== current) element.setAttribute(attribute, translated);
  }

  function applyLanguage(language = getLanguage()) {
    document.documentElement.lang = language;
    document.querySelectorAll('input, textarea, select').forEach(element => {
      if (element.labels) {
        element.labels.forEach(label => {
          label.childNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, language);
          });
        });
      }
    });
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node, language);
    document.querySelectorAll('[aria-label], [title], [placeholder]').forEach(element => {
      ['aria-label', 'title', 'placeholder'].forEach(attribute =>
        translateAttribute(element, attribute, language));
    });
    document.querySelectorAll('#language-toggle [data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
  }

  function setLanguage(language) {
    const selected = language === 'sv' ? 'sv' : 'en';
    try {
      localStorage.setItem('nexa-language', selected);
    } catch (_) {
      // The selected language still applies for this page if storage is unavailable.
    }
    applyLanguage(selected);
  }

  document.addEventListener('click', event => {
    const button = event.target.closest('#language-toggle [data-language]');
    if (button) setLanguage(button.dataset.language);
  });

  const observer = new MutationObserver(records => {
    const language = getLanguage();
    if (language === 'en') return;
    records.forEach(record => {
      if (record.type === 'characterData') {
        translateTextNode(record.target, language);
      } else if (record.type === 'attributes') {
        translateAttribute(record.target, record.attributeName, language);
      } else {
        record.addedNodes.forEach(added => {
          if (added.nodeType === Node.TEXT_NODE) {
            translateTextNode(added, language);
          } else if (added.nodeType === Node.ELEMENT_NODE) {
            const walker = document.createTreeWalker(added, NodeFilter.SHOW_TEXT);
            let node;
            while ((node = walker.nextNode())) translateTextNode(node, language);
            ['aria-label', 'title', 'placeholder'].forEach(attribute => {
              if (added.hasAttribute(attribute)) translateAttribute(added, attribute, language);
            });
            added.querySelectorAll('[aria-label], [title], [placeholder]').forEach(element => {
              ['aria-label', 'title', 'placeholder'].forEach(attribute =>
                translateAttribute(element, attribute, language));
            });
          }
        });
      }
    });
  });

  if (document.body) {
    applyLanguage();
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['aria-label', 'title', 'placeholder'],
    });
  }

  window.NexaI18n = {applyLanguage, setLanguage, translate: translateValue};
